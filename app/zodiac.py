"""
zodiac.py
---------
คำนวณ zodiac_sign (ราศี) และ zodiac_animal (ปีนักษัตร) จาก birth_date (+
เวลาเกิดถ้ามี) เท่านั้น ผู้ใช้ไม่กรอกค่าพวกนี้เอง — ระบบคำนวณให้ ตามที่ตกลง
ไว้ในสโคปของ user_astro_profiles

zodiac_sign ตอนนี้ใช้สูตรสุริยยาตร์ไทยจริงจาก `suriyayart.py` (พระคัมภีร์
สุริยยาตรศิวาคม) แทนสูตรสากล (tropical) ชั่วคราวที่ใช้ไปก่อนหน้านี้แล้ว —
คำนวณจากตำแหน่งดวงอาทิตย์จริงตามปฏิทินจันทรคติไทย ไม่ใช่แค่ช่วงวันที่ตาม
ปฏิทินสุริยคติแบบสากล

เวลาเกิดมีผลต่อผลลัพธ์จริง (ราศีอาจเปลี่ยนได้ถ้าเกิดใกล้ช่วงเปลี่ยนราศีพอดี
ในวันนั้น) ถ้าผู้ใช้ไม่ทราบเวลาเกิด ใช้ 12:00 น. (เที่ยงวัน) เป็นค่ากลาง
เริ่มต้น — เป็นธรรมเนียมมาตรฐานที่ซอฟต์แวร์โหราศาสตร์ทั่วไปใช้กันเวลาไม่ทราบ
เวลาเกิดจริง (ลดความเสี่ยงผิดพลาดเฉลี่ยเมื่อเทียบกับเดาสุ่มเป็นเช้า/เย็น)
"""

from datetime import date

from . import suriyayart

ZODIAC_ANIMALS = [
    "ชวด", "ฉลู", "ขาล", "เถาะ", "มะโรง", "มะเส็ง",
    "มะเมีย", "มะแม", "วอก", "ระกา", "จอ", "กุน",
]

DEFAULT_TIME_FRAC = 0.5  # เที่ยงวัน (12:00) — ใช้เมื่อไม่ทราบเวลาเกิดจริง


def calculate_zodiac_animal(birth_date: date) -> str:
    """ปีนักษัตรไทย วนรอบ 12 ปี อิง พ.ศ./ค.ศ. ปีเกิด (2020 = ปีชวด เป็นจุดอ้างอิง)
    เป็นการนับรอบปีปฏิทินธรรมดา ไม่เกี่ยวกับตำแหน่งดาว จึงไม่ต้องใช้สูตร
    สุริยยาตร์ (ต่างจาก zodiac_sign)"""
    reference_year = 2020  # ปีชวด (ค.ศ.)
    offset = (birth_date.year - reference_year) % 12
    return ZODIAC_ANIMALS[offset]


def calculate_zodiac_sign(birth_date: date, time_frac: float = DEFAULT_TIME_FRAC) -> str:
    """ราศีตามสูตรสุริยยาตร์ไทย (ตำแหน่งดวงอาทิตย์จริง ไม่ใช่ช่วงวันที่สากล)

    time_frac: สัดส่วนของวัน (0.0 = เที่ยงคืน, 0.5 = เที่ยงวัน, ...) —
    คำนวณจาก (ชั่วโมง + นาที/60) / 24 ถ้าทราบเวลาเกิด ไม่งั้นปล่อยเป็นค่า
    default (เที่ยงวัน)
    """
    rasi_idx, _degree, _libda = suriyayart.sun_rasi(
        birth_date.day, birth_date.month, birth_date.year, time_frac
    )
    return suriyayart.RASI_NAMES[rasi_idx]
