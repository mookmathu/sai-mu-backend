def seed() -> None:
    Base.metadata.create_all(bind=engine)
    db = SessionLocal()
    try:
        existing = {n for (n,) in db.query(models.SacredPlace.name).all()}
        added = 0
        for p in PLACES:
            if p["name"] in existing:
                continue
            db.add(models.SacredPlace(province="กรุงเทพมหานคร", source_note=NOTE, **p))
            added += 1
        db.commit()
        print(f"เพิ่มสถานที่ใหม่ {added} แห่ง (ข้าม {len(PLACES) - added} แห่งที่มีชื่อซ้ำอยู่แล้ว)")
        print("⚠️ พิกัดเป็นค่าประมาณ — ตรวจกับ Google Maps แล้วแก้ในหน้า /admin/ ได้")
    finally:
        db.close()


if __name__ == "__main__":
    seed()
