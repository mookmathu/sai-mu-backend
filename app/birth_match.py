"""
birth_match.py
--------------
เทียบ "เลขของชื่อ / เบอร์ / ทะเบียน" กับ "เลขประจำวันเกิด" ของผู้ใช้ (ต้อง login และมีวันเกิดในโปรไฟล์)

หลักการ (ตามข้อความเลขศาสตร์ในฐานความรู้ number-1..9, number-100):
- เลขดาว 1-9: 1 อาทิตย์, 2 จันทร์, 3 อังคาร, 4 พุธ, 5 พฤหัสบดี, 6 ศุกร์, 7 เสาร์, 8 ราหู, 9 เกตุ
- เลขประจำวันเกิดตามวันในสัปดาห์: อาทิตย์=1 จันทร์=2 อังคาร=3 พุธ=4 พฤหัสบดี=5 ศุกร์=6 เสาร์=7
  (พุธกลางคืนตามตำราเป็นราหู เลข 8 แต่ระบบยังไม่ทราบเวลาแบ่งกลางวัน-กลางคืนที่ชัดเจน จึงนับเป็น 4 ทุกกรณี)
- เลขของชื่อ/เบอร์ = ผลรวมที่บวกกันจนเหลือหลักเดียว (เช่น 44 → 8 ตามที่ตำราเขียนว่า "รวมกันได้ 8")
- คู่มิตร/คู่ศัตรูของแต่ละเลข ตามข้อความในตำรา (ถ้าฝ่ายใดฝ่ายหนึ่งระบุว่าเป็นมิตรและไม่มีฝ่ายใดระบุศัตรู = มิตร,
  ระบุศัตรู = ศัตรู, ไม่ระบุเลย = ไม่ได้ระบุไว้) ผลเป็นความเชื่อตามตำรา ไม่ใช่การกำหนดชะตา
"""
from __future__ import annotations

from datetime import date

PLANET = {1: "อาทิตย์", 2: "จันทร์", 3: "อังคาร", 4: "พุธ", 5: "พฤหัสบดี", 6: "ศุกร์", 7: "เสาร์", 8: "ราหู", 9: "เกตุ"}

# date.weekday(): จันทร์=0 ... อาทิตย์=6
_WEEKDAY = {6: ("วันอาทิตย์", 1), 0: ("วันจันทร์", 2), 1: ("วันอังคาร", 3), 2: ("วันพุธ", 4),
            3: ("วันพฤหัสบดี", 5), 4: ("วันศุกร์", 6), 5: ("วันเสาร์", 7)}

FRIENDS = {1: {2, 5}, 2: {4}, 3: {6}, 4: {2}, 5: {1}, 6: {3}, 7: {8}, 8: {7}, 9: {9}}
ENEMIES = {1: {3}, 2: {3, 7, 8, 9}, 3: {1}, 4: {3, 8}, 5: {3, 7, 8}, 6: {7, 8, 9}, 7: {3, 6}, 8: {4, 6}, 9: set()}


def digit_root(n: int) -> int:
    """บวกเลขทุกหลักซ้ำจนเหลือหลักเดียว (0 → 0)"""
    n = abs(int(n))
    while n > 9:
        n = sum(int(c) for c in str(n))
    return n


def relation(a: int, b: int) -> str:
    """same | friend | enemy | neutral ระหว่างเลขดาว a กับ b (1-9)"""
    if a == b:
        return "same"
    friend = b in FRIENDS.get(a, set()) or a in FRIENDS.get(b, set())
    enemy = b in ENEMIES.get(a, set()) or a in ENEMIES.get(b, set())
    if enemy and not friend:
        return "enemy"
    if friend and not enemy:
        return "friend"
    if friend and enemy:
        return "neutral"
    return "neutral"


_TEXT = {
    "same": ("เลขเดียวกับวันเกิด",
             "เลขนี้ตรงกับเลขประจำวันเกิดของคุณ ตำราถือว่าเป็นเลขเดียวกันซ้อนกัน ทำให้อิทธิพลของเลขนั้นเด่นชัดขึ้น "
             "ถ้าเป็นเลขดีก็ส่งเสริมมาก ถ้าเป็นเลขที่ควรระวังก็ควรระวังเป็นพิเศษ"),
    "friend": ("เป็นคู่มิตรกับวันเกิด",
               "เลขนี้เป็นคู่มิตรกับเลขประจำวันเกิดของคุณ ตำราถือว่าส่งเสริมกัน อยู่ด้วยกันแล้วเกื้อกูลกันดี"),
    "enemy": ("เป็นคู่ศัตรูกับวันเกิด",
              "เลขนี้เป็นคู่ศัตรูกับเลขประจำวันเกิดของคุณ ตำราว่าเข้ากันไม่ค่อยดี อยู่ด้วยกันแล้วไม่ค่อยส่งเสริม "
              "ถ้ากังวลอาจเลือกเลขที่เป็นมิตรกับวันเกิดแทน แต่ทั้งหมดเป็นเพียงความเชื่อตามตำรา"),
    "neutral": ("ไม่ได้เป็นคู่มิตรหรือคู่ศัตรูโดยตรง",
                "ตำราไม่ได้ระบุว่าเลขนี้เป็นคู่มิตรหรือคู่ศัตรูกับเลขประจำวันเกิดของคุณโดยตรง จึงถือว่าเป็นกลาง ๆ"),
}


def match_with_birth(total: int, birth_date: date | None) -> dict | None:
    """คืนผลเทียบกับวันเกิด หรือ None ถ้าไม่มีวันเกิด/ผลรวมเป็น 0"""
    if birth_date is None or not total:
        return None
    n = digit_root(total)
    if n == 0:
        return None
    day_name, b = _WEEKDAY[birth_date.weekday()]
    rel = relation(n, b)
    headline, text = _TEXT[rel]
    return {
        "birth_day_name": day_name,
        "birth_number": b,
        "birth_planet": PLANET[b],
        "name_number": n,
        "name_planet": PLANET[n],
        "relation": rel,
        "headline": headline,
        "text": text,
    }
