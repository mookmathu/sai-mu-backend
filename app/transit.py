    # ทดสอบเร็ว ๆ: คนเกิดราศีตุลย์ (ตามตัวอย่างที่เห็นในโปรไฟล์จริงของแอป) ดูดวงวันนี้
    today = date.today()
    house_no, house_name = calculate_transit_house("ตุลย์", today)
    print(f"วันที่ {today} — จันทร์เคลื่อนเข้าภพที่ {house_no} ({house_name}) นับจากราศีตุลย์")

    # ทวนซ้ำอีก 3 วันติดกันให้เห็นว่าเปลี่ยนภพจริงเมื่อจันทร์ย้ายราศี (ทุก ~2.25 วัน)
    from datetime import timedelta

    for offset in range(1, 4):
        d = today + timedelta(days=offset)
        house_no, house_name = calculate_transit_house("ตุลย์", d)
        print(f"วันที่ {d} — ภพที่ {house_no} ({house_name})")
