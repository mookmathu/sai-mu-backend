from datetime import date

from . import suriyayart

HOUSE_NAMES = [
    "ตนุ", "กฎุมพะ", "สหัชชะ", "พันธุ", "ปุตตะ", "อริ",
    "ปัตนิ", "มรณะ", "ศุภะ", "กัมมะ", "ลาภะ", "วินาสนะ",
]

# แปลงชื่อราศี (ใช้ใน suriyayart.RASI_NAMES) กลับเป็นดัชนี 0-11 — ใช้ตอนรับ
# zodiac_sign (string) ที่เก็บไว้ใน user_astro_profiles มาแปลงกลับเป็นตัวเลขก่อนคำนวณ
RASI_NAME_TO_INDEX = {name: idx for idx, name in enumerate(suriyayart.RASI_NAMES)}


def calculate_transit_house(
    natal_sun_rasi: str | int,
    target_date: date,
    time_frac: float = 0.5,
) -> tuple[int, str]:
    """คืนค่า (เลขภพ 1-12, ชื่อภพ) ของดวงจันทร์ ณ target_date เทียบกับราศีอาทิตย์กำเนิด

    natal_sun_rasi: รับได้ทั้งชื่อราศีภาษาไทย (เช่น "ตุลย์" ตามที่เก็บใน zodiac_sign ของ
    ผู้ใช้) หรือดัชนีตัวเลข 0-11 โดยตรง
    target_date: วันที่ต้องการทำนาย (เช่น วันนี้ สำหรับดวงประจำวัน)
    time_frac: ค่าเวลาแบบสัดส่วนของวัน ปกติใช้เที่ยงวัน (0.5) ก็เพียงพอ เพราะจันทร์เปลี่ยน
    ราศีเฉลี่ยทุก ๆ 2.25 วัน ความคลาดเคลื่อนจากเวลาในหนึ่งวันมีผลน้อยมาก
    """
    if isinstance(natal_sun_rasi, str):
        natal_idx = RASI_NAME_TO_INDEX[natal_sun_rasi]
    else:
        natal_idx = natal_sun_rasi

    moon_rasi_idx, _degree, _libda = suriyayart.moon_rasi(
        target_date.day, target_date.month, target_date.year, time_frac
    )

    # นับภพแบบไทย: ราศีอาทิตย์กำเนิด = ภพที่ 1 (ตนุ) แล้ววนไปตามลำดับราศีจนถึงราศีจันทร์ปัจจุบัน
    house_number = (moon_rasi_idx - natal_idx) % 12 + 1
    house_name = HOUSE_NAMES[house_number - 1]
    return house_number, house_name


# ---------------------------------------------------------------------
# ดวงเจาะจงหัวข้อ (เช่น "ดวงความรักช่วงนี้") — ต่างจาก calculate_transit_house()
# ตรงที่ calculate_transit_house() บอกแค่ "วันนี้ดวงจันทร์อยู่ภพไหนโดยรวม" ซึ่งอาจไม่ใช่
# ภพที่เกี่ยวกับหัวข้อที่ถามเลยก็ได้ (เช่นถามเรื่องความรักแต่วันนี้จันทร์ดันอยู่ภพที่ 3
# ซึ่งเป็นเรื่องพี่น้อง ไม่เกี่ยวกับความรักเลย) — ฟังก์ชันนี้จะคำนวณ "มุมสัมพันธ์" ระหว่าง
# ดวงจันทร์ปัจจุบันกับ "ภพของหัวข้อนั้นในดวงกำเนิด" โดยตรง แทน เพื่อให้ตอบเจาะจงหัวข้อได้
# เทคนิคนี้ยังคงใช้แค่สูตรสุริยยาตร์เดิม (ไม่มีปัญหาลิขสิทธิ์ Swiss Ephemeris เหมือนเดิม)
# ---------------------------------------------------------------------

# ชื่อมุมสัมพันธ์เรียงตามระยะห่างราศี (0-6 ราศี, พับครึ่งวงกลม 12 ราศีแล้ว เพราะมุมมองจาก
# ทั้งสองทิศทางรอบวงจักรราศีให้ความหมายเดียวกัน) — อิงตารางมุมสัมพันธ์แบบไทยมาตรฐาน
ASPECT_NAMES = ["กุม", "ใกล้ชิด", "โยค", "เล็ง", "ตรีโกณ", "กระทบ", "เล็งตรง"]

# คำที่ใช้จับหัวข้อที่ผู้ใช้ถาม แล้วจับคู่กับภพที่เกี่ยวข้องตามหลักโหราศาสตร์ไทย
# (ตนุ=1 สุขภาพ/ตัวเอง, กฎุมพะ=2 การเงิน, สหัชชะ=3 พี่น้อง/เดินทางใกล้, พันธุ=4 ครอบครัว/
# ที่อยู่อาศัย, ปุตตะ=5 การเรียน/ความคิดสร้างสรรค์, อริ=6 ศัตรู/อุปสรรค, ปัตนิ=7 คู่ครอง/
# ความรัก, มรณะ=8 การเปลี่ยนแปลงใหญ่, ศุภะ=9 โชคลาภ/บารมี, กัมมะ=10 การงาน,
# ลาภะ=11 เพื่อน/บริวาร, วินาสนะ=12 รายจ่าย/อุปสรรคซ่อนเร้น)
TOPIC_KEYWORDS_TO_HOUSE: dict[str, int] = {
    "ความรัก": 7, "คู่รัก": 7, "แฟน": 7, "คู่ครอง": 7, "สามีภรรยา": 7,
    "เนื้อคู่": 7, "คู่ชีวิต": 7,
    "คืนดี": 7, "เลิกกัน": 7, "ง้อ": 7, "คนรัก": 7, "แต่งงาน": 7, "จีบ": 7,
    "การงาน": 10, "งาน": 10, "อาชีพ": 10, "หน้าที่การงาน": 10,
    "การเงิน": 2, "เงินทอง": 2, "ทรัพย์สิน": 2, "รายได้": 2,
    "สุขภาพ": 1,
    "ครอบครัว": 4, "บ้าน": 4, "ที่อยู่อาศัย": 4,
    "การเรียน": 5, "เรียน": 5,
    "เพื่อน": 11, "บริวาร": 11, "ผู้ใต้บังคับบัญชา": 11,
    "ศัตรู": 6, "คู่แข่ง": 6, "อุปสรรค": 6,
    "การเดินทาง": 3, "เดินทาง": 3, "พี่น้อง": 3,
}


def detect_topic_house(question: str) -> tuple[str, int] | None:
    """เช็คว่าคำถามเอ่ยหัวข้อที่จับคู่กับภพใดภพหนึ่งไหม คืน (คำที่เจอ, เลขภพ) หรือ
    None ถ้าไม่เจอหัวข้อเจาะจง (ให้ผู้เรียกไป fallback ใช้ calculate_transit_house()
    แบบทั่วไปแทน)"""
    for keyword, house_number in TOPIC_KEYWORDS_TO_HOUSE.items():
        if keyword in question:
            return keyword, house_number
    return None


def calculate_topic_transit(
    natal_sun_rasi: str | int,
    topic_house_number: int,
    target_date: date,
    time_frac: float = 0.5,
) -> tuple[str, str]:
    """คืนค่า (ชื่อมุมสัมพันธ์, ชื่อภพของหัวข้อ) — คำนวณมุมระหว่างราศีที่ดวงจันทร์อยู่
    ณ target_date กับราศีของภพหัวข้อที่ถาม (นับจากราศีอาทิตย์กำเนิด) เพื่อบอกว่าช่วงนี้
    ดวงจันทร์ "ส่งอิทธิพล" อะไรมาสู่เรื่องนั้นในดวงกำเนิดของผู้ใช้"""
    if isinstance(natal_sun_rasi, str):
        natal_idx = RASI_NAME_TO_INDEX[natal_sun_rasi]
    else:
        natal_idx = natal_sun_rasi

    moon_rasi_idx, _degree, _libda = suriyayart.moon_rasi(
        target_date.day, target_date.month, target_date.year, time_frac
    )

    topic_rasi_idx = (natal_idx + topic_house_number - 1) % 12
    raw_distance = (moon_rasi_idx - topic_rasi_idx) % 12
    aspect_step = min(raw_distance, 12 - raw_distance)  # พับครึ่งวงกลม 0-6

    aspect_name = ASPECT_NAMES[aspect_step]
    topic_house_name = HOUSE_NAMES[topic_house_number - 1]
    return aspect_name, topic_house_name


