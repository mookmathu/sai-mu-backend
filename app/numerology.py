def is_birthdate_numerology_question(question: str) -> bool:
    """เช็คว่าคำถามนี้กำลังถามเรื่อง "เลขศาสตร์วันเกิด" ของตัวเองไหม — ครอบคลุมทั้ง
    คำเฉพาะทาง (เลขวันเกิด/เลขชีวิต/เลขนำโชค) และคำถามกำกวมแบบ "เลขของฉันคืออะไร"/
    "เลขผมคืออะไร" ที่ไม่ได้พิมพ์เบอร์/ทะเบียน/ชื่อมาให้เลย ซึ่งควรตีความว่าหมายถึง
    เลขวันเกิดที่ระบบมีอยู่แล้ว แทนที่จะปล่อยให้ semantic search ทั่วไปสุ่มเอาเนื้อหาที่
    ไม่เกี่ยวข้องมาตอบ (หรือแย่กว่านั้นคือโดนกลไกปฏิเสธนอกขอบเขตเข้าใจผิดว่าไม่เกี่ยวข้อง)"""
    if any(kw in question for kw in BIRTHDATE_NUMEROLOGY_KEYWORDS):
        return True
    q = question.replace(" ", "")
    if "เลข" not in q:
        return False
    if "วันเกิด" in q:
        return True
    return any(pronoun in q for pronoun in _PERSONAL_PRONOUNS)


def extract_birthdate_digits(birth_date: date) -> str:
    """แปลงวันเกิดเป็นสตริงตัวเลขล้วนๆ 8 หลัก: วัน(2) + เดือน(2) + ปี พ.ศ.(4)
    เช่น เกิด 5 มี.ค. ค.ศ. 1999 (พ.ศ. 2542) -> "05032542" """
    year_be = birth_date.year + _BUDDHIST_ERA_OFFSET
    return f"{birth_date.day:02d}{birth_date.month:02d}{year_be:04d}"


def calculate_birthdate_number(birth_date: date) -> dict:
    """คำนวณเลขศาสตร์วันเกิด: รวมค่าตัวเลขทุกหลักของวันเดือนปีเกิด (พ.ศ.) เป็นเลข
    เดียว แล้วลดทอนให้อยู่ในช่วง 0-100 ด้วยกฎเดียวกับ calculate_name_number()
    (ในทางปฏิบัติผลรวมของ 8 หลักจะไม่มีทางเกิน 100 อยู่แล้ว — เรียก reduce_name_total
    ไว้เผื่ออนาคตเปลี่ยนวิธีคำนวณเป็นอย่างอื่นที่อาจได้ผลรวมสูงกว่านี้)
    คืน dict:
        {
            "digits": "05031999",
            "raw_total": 27,
            "final_number": 27,
        }
    """
    digits = extract_birthdate_digits(birth_date)
    raw_total = sum(int(d) for d in digits)
    final_number = reduce_name_total(raw_total)
    return {
        "digits": digits,
        "raw_total": raw_total,
        "final_number": final_number,
    }
