def letter_value(char: str) -> int | None:
    """คืนค่าตัวเลขของอักษรไทย 1 ตัว (พยัญชนะหรือสระที่มีในตาราง) หรือ None ถ้าไม่ใช่
    อักษรที่มีค่ากำหนดไว้ (เช่น ช่องว่าง อักษรภาษาอื่น หรือสระ/วรรณยุกต์ที่ตำราไม่ได้
    ระบุค่า)"""
    if char in THAI_CONSONANT_VALUES:
        return THAI_CONSONANT_VALUES[char]
    if char in THAI_VOWEL_VALUES:
        return THAI_VOWEL_VALUES[char]
    return None


def reduce_name_total(total: int) -> int:
    """ลดทอนผลรวมที่เกิน 100 ให้อยู่ในช่วงที่มี chunk ความหมายรองรับ (0-100) ตามกฎ
    ที่ใช้กันทั่วไปในเลขศาสตร์ไทย:
        - 101-109 (หลักสิบเป็น 0): ตัดเหลือ "หลักร้อย+หลักหน่วย" เช่น 109 -> 19
        - 110 ขึ้นไป: ตัดเหลือ "หลักสิบ+หลักหน่วย" เช่น 115 -> 15, 124 -> 24
    ถ้า total <= 100 อยู่แล้ว คืนค่าเดิมโดยไม่แตะต้อง"""
    if total <= 100:
        return total
    tens_digit = (total // 10) % 10
    units_digit = total % 10
    if tens_digit == 0:
        hundreds_digit = total // 100
        return hundreds_digit * 10 + units_digit
    return tens_digit * 10 + units_digit


def calculate_name_number(name: str) -> dict:
    """คำนวณเลขศาสตร์ชื่อ: รวมค่าตัวอักษรทุกตัวในชื่อที่มีค่ากำหนดไว้ แล้วลดทอนผลรวม
    ให้อยู่ในช่วง 0-100 คืน dict:
        {
            "name": "มัทรา",
            "letter_values": [("ม", 5), ("ั", 4), ("ท", 1), ("ร", 4), ("า", 1)],
            "skipped_chars": [],       # อักษรที่ไม่มีค่ากำหนด (ถ้ามี)
            "raw_total": 15,
            "final_number": 15,        # หลังลดทอนแล้ว (ใช้ไปดึง chunk number-{n})
        }
    """
    name = name.strip()
    letter_values: list[tuple[str, int]] = []
    skipped_chars: list[str] = []

    for char in name:
        value = letter_value(char)
        if value is None:
            if not char.isspace():
                skipped_chars.append(char)
            continue
        letter_values.append((char, value))

    raw_total = sum(value for _, value in letter_values)
    final_number = reduce_name_total(raw_total)

    return {
        "name": name,
        "letter_values": letter_values,
        "skipped_chars": skipped_chars,
        "raw_total": raw_total,
        "final_number": final_number,
    }


