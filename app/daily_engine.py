def lunar_phase(today: date) -> dict | None:
    """ข้างขึ้น/ข้างแรม จากมุมระหว่างอาทิตย์-จันทร์ ณ เที่ยงวัน (สุริยยาตร์)"""
    try:
        si, sd, sl = suriyayart.sun_rasi(today.day, today.month, today.year, 0.5)
        mi, md, ml = suriyayart.moon_rasi(today.day, today.month, today.year, 0.5)
    except Exception:
        return None
    sun = si * 30 + sd + sl / 60
    moon = mi * 30 + md + ml / 60
    tithi = int(((moon - sun) % 360) // 12) + 1  # 1..30
    if tithi in (14, 15, 16):
        return {"name": "ใกล้วันเพ็ญ", "waxing": True,
                "text": "ดวงจันทร์ใกล้เต็มดวง อารมณ์คนมักเด่นกว่าปกติ ทั้งความตื่นเต้นและความอ่อนไหว"}
    if tithi >= 29 or tithi <= 1:
        return {"name": "ใกล้วันดับ", "waxing": False,
                "text": "ดวงจันทร์ใกล้ดับ พลังอยู่ในช่วงเงียบ เหมาะกับการสะสางของเก่าและพักใจ"}
    if tithi <= 15:
        return {"name": "ข้างขึ้น", "waxing": True,
                "text": "ดวงจันทร์ข้างขึ้น พลังกำลังเพิ่ม เหมาะกับการเริ่มเรื่องใหม่"}
    return {"name": "ข้างแรม", "waxing": False,
            "text": "ดวงจันทร์ข้างแรม พลังกำลังลด เหมาะกับการสะสางเรื่องค้างและทำของเดิมให้เสร็จ"}


def _moon_idx(d: date, tf: float = 0.5) -> int:
    return suriyayart.moon_rasi(d.day, d.month, d.year, tf)[0]


def natal_moon_index(birth_date: date, birth_time: time | None) -> int | None:
    """ราศีของจันทร์ตอนเกิด — ต้องมีเวลาเกิด (ไม่เดาถ้าไม่ทราบ)"""
    if birth_time is None:
        return None
    tf = (birth_time.hour + birth_time.minute / 60) / 24
    return suriyayart.moon_rasi(birth_date.day, birth_date.month, birth_date.year, tf)[0]


