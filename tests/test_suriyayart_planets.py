def test_planets_match_workbook():
    for (d, m, y, hh, mm), expected in CASES:
        got = sp.planets_sompus(d, m, y, (hh + mm / 60) / 24)
        for name, value in expected.items():
            assert abs(got[name] - value) < 1e-6, ((d, m, y, hh, mm), name, got[name], value)


def test_rasi_in_range():
    r = sp.planets_rasi(22, 10, 2026, 0.5)
    assert set(r) == set(sp.PLANET_ID)
    for idx, deg, lib in r.values():
        assert 0 <= idx <= 11 and 0 <= deg < 30 and 0 <= lib < 60


